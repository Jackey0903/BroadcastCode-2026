def _canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def store_digest(store):
    return hashlib.sha256(_canonical({"players": store["players"], "records": store["records"]}).encode()).hexdigest()


def validate_store(store):
    if store.get("schema") != "rl-scout-evidence-store-v1":
        raise ValueError("Unsupported evidence store")
    players = {str(p["playerId"]): p for p in store["players"]}
    if len(players) != len(store["players"]) or any(int(p["teamId"]) not in TEAMS for p in players.values()):
        raise ValueError("Player cohort must contain unique HOU/DAL identities")
    ids = set()
    for record in store["records"]:
        eid, pid = record["evidenceId"], str(record["playerId"])
        if not isinstance(eid, str) or not eid or eid in ids or pid not in players:
            raise ValueError("Unknown player or duplicate/invalid evidence ID")
        ids.add(eid)
        if record["family"] not in TOOLS or int(record["teamId"]) not in TEAMS:
            raise ValueError("Unexpected source family/team")
        if int(record["teamId"]) != int(players[pid]["teamId"]):
            raise ValueError("Record/player team label mismatch")
        value = record.get("value")
        duration = (record["family"] == "basic" and record["metric"] == "MIN" and record.get("unit") == "mm:ss"
                    and isinstance(value, str) and re.fullmatch(r"\d{1,3}:[0-5]\d", value))
        if value is not None and not duration and (isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value)):
            raise ValueError("Evidence values must be finite numbers or missing")
        if record["grain"] not in {"player-game", "player-season"}:
            raise ValueError("Unsupported evidence grain")
        if record["family"] in {"basic", "advanced"} and (record["grain"] != "player-game" or not record.get("gameId")):
            raise ValueError("Game statistics require a game ID")
        if record["family"] not in {"basic", "advanced"} and record["grain"] != "player-season":
            raise ValueError("Depth snapshots must remain player-season")
        source = record.get("source", {})
        if not all(source.get(k) for k in ("url", "sha256", "rowKey", "retrievedAt")):
            raise ValueError("Missing source provenance")
    return True


def split_players(players):
    """Stratified deterministic source-player groups; Flagg's known clip is development."""
    assignments = {}
    for team in sorted(TEAMS):
        pids = sorted((str(p["playerId"]) for p in players if int(p["teamId"]) == team),
                      key=lambda pid: hashlib.sha256(("evidence-split-v1:" + pid).encode()).hexdigest())
        count = max(1, round(len(pids) * 0.15)) if len(pids) >= 3 else 0
        for i, pid in enumerate(pids):
            assignments[pid] = "val" if i < count else "test" if i < 2 * count else "train"
        if "1642843" in pids and assignments["1642843"] != "val" and count:
            previous = assignments["1642843"]
            swap = next(pid for pid in pids if assignments[pid] == "val")
            assignments[swap], assignments["1642843"] = previous, "val"
    return assignments


def _records(store, pid, family, game_id=None):
    rows = [r for r in store["records"] if str(r["playerId"]) == str(pid) and r["family"] == family
            and r.get("value") is not None and (family not in {"basic", "advanced"} or r.get("gameId") == game_id)]
    preference = PREFERRED[family]
    rows.sort(key=lambda r: (preference.index(r["metric"]) if r["metric"] in preference else len(preference),
                             r["metric"], r["evidenceId"]))
    return rows[:12 if family in {"basic", "advanced"} else 13]


def _task(store_hash, player, split, category, prompt, families, records=(), relations=(), game_id=None,
          reason=None, as_of=None, requested_grain=None):
    request = {"playerId": str(player["playerId"]), "gameId": game_id, "asOf": as_of,
               "requestedGrain": requested_grain, "causal": category == "causal_boundary"}
    answer = {"status": "unavailable" if reason else "ok", "evidenceIds": [] if reason else sorted(r["evidenceId"] for r in records),
              "relations": [] if reason else sorted(relations), "reasonCode": reason}
    fingerprint = {"request": request, "prompt": prompt, "answer": answer, "storeSha256": store_hash}
    return {"schema": SCHEMA, "id": hashlib.sha256(_canonical(fingerprint).encode()).hexdigest()[:20],
            "split": split, "category": category, "prompt": prompt, "request": request,
            "storeSha256": store_hash,
            "oracle": {"answer": answer, "requiredFamilies": list(families),
                       "requiredEvidenceIds": answer["evidenceIds"], "requiredRelations": answer["relations"]}}


def make_tasks(store):
    validate_store(store)
    digest, groups, tasks = store_digest(store), split_players(store["players"]), []
    game_order = {game: i for i, game in enumerate(sorted({r["gameId"] for r in store["records"] if r.get("gameId")}))}
    for player in sorted(store["players"], key=lambda p: str(p["playerId"])):
        pid, split = str(player["playerId"]), groups[str(player["playerId"])]
        def add(category, prompt, families, **kwargs):
            tasks.append(_task(digest, player, split, category, prompt, families, **kwargs))
        depth = {family: _records(store, pid, family) for family in TOOLS[2:]}
        for family, rows in depth.items():
            if not rows:
                concept = LABELS[PREFERRED[family][0]]
                add("missing_family", f"查询这名球员赛季的{concept}；没有官方记录时说明缺失。", [family], reason="metric_not_available")
                continue
            for row in rows:
                add("depth_lookup", f"这名球员赛季的{LABELS.get(row['metric'], row['metric'])}应引用哪条官方记录？", [family], records=[row])
            concept = LABELS.get(rows[0]["metric"], rows[0]["metric"])
            add("event_boundary", f"请给出视频这一次进攻中的{concept}测量值，不能用赛季平均替代。", [family],
                reason="event_granularity_not_available", requested_grain="event")
        if depth["gravity"]:
            add("causal_boundary", "官方数据能否证明这名球员导致了视频这一回合队友的空位？请选择支撑这种因果结论的证据。",
                ["gravity"], reason="causal_evidence_not_available", requested_grain="event")
        historical = next((family for family, rows in depth.items() if rows and any(r.get("asOf") is None for r in rows)), None)
        if historical:
            concept = LABELS.get(depth[historical][0]["metric"], depth[historical][0]["metric"])
            add("as_of_boundary", f"只使用2026-01-04开赛前已知资料，查询球员的{concept}，不得使用赛后完整赛季快照。",
                [historical], reason="historical_as_of_not_available", as_of="2026-01-04")
        games = sorted({r["gameId"] for r in store["records"] if str(r["playerId"]) == pid
                        and r["family"] in {"basic", "advanced"} and r.get("gameId")})
        for game in games:
            basic, advanced = _records(store, pid, "basic", game), _records(store, pid, "advanced", game)
            if basic:
                add("basic_lookup", f"查询这名球员本场的{LABELS.get(basic[0]['metric'], basic[0]['metric'])}。",
                    ["basic"], records=[basic[0]], game_id=game)
            if advanced:
                add("advanced_lookup", f"本场{LABELS.get(advanced[0]['metric'], advanced[0]['metric'])}应该参考哪个指标？",
                    ["advanced"], records=[advanced[0]], game_id=game)
            if not basic or not advanced:
                continue
            index = game_order[game]
            basic_metric = ("PTS", "AST", "REB")[index % 3]
            advanced_metric = ("TS_PCT", "EFG_PCT")[index % 2]
            main = [next((r for r in basic if r["metric"] == basic_metric), basic[0]),
                    next((r for r in advanced if r["metric"] == advanced_metric), advanced[0])]
            performance = LABELS.get(main[0]["metric"], main[0]["metric"])
            efficiency = LABELS.get(main[1]["metric"], main[1]["metric"])
            add("basic_advanced", f"同时选择本场{performance}和{efficiency}证据，说明它们提供互补背景。",
                ["basic", "advanced"], records=main, relations=["volume_efficiency_context"], game_id=game)
            for family, rows in depth.items():
                if not rows:
                    continue
                depth_metric = {"gravity": ("OFF_BALL_PERIM_GRAV", "ON_BALL_PERIM_GRAV", "OFF_BALL_INTERIOR_GRAV")[index % 3],
                                "leverage": ("OFF_LVG", "CREATION_LVG", "REB_LVG", "DEF_LVG")[index % 4],
                                "shotdifficulty": ("AVGSHOTQUALITY", "FGPCTABOVEEXPECTED")[index % 2]}[family]
                context = next((r for r in rows if r["metric"] == depth_metric), rows[0])
                concept = LABELS.get(context["metric"], context["metric"])
                add("joint_three_layer", f"先选本场{performance}和{efficiency}证据，再补充赛季{concept}背景。"
                    "保留本场与赛季两个范围，给出互补关系，不作因果归因。", ["basic", "advanced", family],
                    records=main + [context], relations=["volume_efficiency_context", RELATION_FOR[family]], game_id=game)
    if len({t["id"] for t in tasks}) != len(tasks):
        raise ValueError("Duplicate derived task IDs")
    return tasks


def policy_view(task):
    request = task["request"]
    game = request.get("gameId") or "未指定比赛；只按问题要求使用现有统计范围"
    return f"球员ID：{request['playerId']}；比赛ID：{game}。\n{task['prompt']}"


def parse_action(text):
    try:
        value = json.loads(text) if isinstance(text, str) else text
    except (ValueError, TypeError):
        return "invalid", None, True
    if not isinstance(value, dict):
        return "invalid", None, True
    if set(value) == {"tools"}:
        names = value["tools"]
        if (not isinstance(names, list) or not names or not all(isinstance(n, str) and n in TOOLS for n in names)
                or len(set(names)) != len(names)):
            return "invalid", None, True
        return "tools", names, False
    if set(value) == ANSWER_KEYS:
        return "answer", value, False
    return "invalid", None, True


class Environment:
    def __init__(self, task, store):
        if task.get("schema") != SCHEMA or task["storeSha256"] != store_digest(store):
            raise ValueError("Task/store version or facts mismatch")
        self.task, self.store, self.trace, self.errors = task, store, [], []

    def execute(self, tool_name, args=None):
        if tool_name not in TOOLS or args not in (None, {}):
            self.errors.append("invalid_tool_or_arguments")
            return {"status": "error", "reasonCode": "invalid_tool_or_arguments", "records": []}
        if len(self.trace) >= MAX_CALLS:
            self.errors.append("tool_budget_exceeded")
            return {"status": "error", "reasonCode": "tool_budget_exceeded", "records": []}
        request = self.task["request"]
        rows = _records(self.store, request["playerId"], tool_name, request.get("gameId"))
        reason = None
        if request.get("causal"):
            reason = "causal_evidence_not_available"
        elif request.get("asOf") and (not rows or any(r.get("asOf") is None or str(r["asOf"])[:10] > request["asOf"] for r in rows)):
            reason = "historical_as_of_not_available"
        elif request.get("requestedGrain") == "event" and (not rows or any(r["grain"] != "event" for r in rows)):
            reason = "event_granularity_not_available"
        elif not rows:
            reason = "metric_not_available"
        visible = [] if reason else [{k: copy.deepcopy(r.get(k)) for k in
            ("evidenceId", "family", "metric", "value", "unit", "grain", "period", "participation")
            if k in r} for r in rows]
        result = {"tool": tool_name, "playerId": request["playerId"], "gameId": request.get("gameId"),
                  "status": "unavailable" if reason else "ok", "reasonCode": reason,
                  "records": visible}
        # Full provenance is retained privately; the model cannot write or replace this trace.
        self.trace.append({"result": copy.deepcopy(result), "sourceRecords": copy.deepcopy(rows)})
        return result

    def score(self, answer, invalid=False):
        if isinstance(answer, str):
            kind, answer, bad = parse_action(answer)
            invalid = invalid or bad or kind != "answer"
        cost = TOOL_COST * len(self.trace)
        parts = {"total": -1.0 - cost, "valid": False, "coverage": 0.0, "fact": 0.0, "evidence": 0.0,
                 "relations": 0.0, "format": 0.0, "schemaValid": False,
                 "toolCalls": len(self.trace), "criticalErrors": list(self.errors)}
        if invalid or not isinstance(answer, dict) or set(answer) != ANSWER_KEYS:
            parts["criticalErrors"].append("invalid_schema")
            return parts
        ids, relations = answer["evidenceIds"], answer["relations"]
        if (not isinstance(answer["status"], str) or answer["status"] not in {"ok", "unavailable"}
                or not isinstance(ids, list) or not isinstance(relations, list)
                or not all(isinstance(x, str) for x in ids + relations)
                or len(set(ids)) != len(ids) or len(set(relations)) != len(relations)
                or not (answer["reasonCode"] is None or isinstance(answer["reasonCode"], str) and answer["reasonCode"] in REASONS)):
            parts["criticalErrors"].append("invalid_schema")
            return parts
        parts["format"] = 1.0
        parts["schemaValid"] = True
        expected = self.task["oracle"]["answer"]
        families = set(self.task["oracle"]["requiredFamilies"])
        actual_families = {item["result"]["tool"] for item in self.trace}
        observed = {r["evidenceId"]: r for item in self.trace if item["result"]["status"] == "ok" for r in item["sourceRecords"]}
        if answer["status"] != expected["status"] or answer["reasonCode"] != expected["reasonCode"]:
            parts["criticalErrors"].append("wrong_availability_or_scope")
        if set(ids) - set(expected["evidenceIds"]) or set(ids) - observed.keys():
            parts["criticalErrors"].append("unreturned_wrong_or_irrelevant_evidence")
        if set(relations) - set(expected["relations"]):
            parts["criticalErrors"].append("unsupported_relation_or_causality")
        if expected["status"] == "unavailable":
            supported = {item["result"]["tool"] for item in self.trace
                         if item["result"]["reasonCode"] == expected["reasonCode"]}
            if ids or relations or not families <= supported:
                parts["criticalErrors"].append("unavailable_without_matching_tool_evidence")
            else:
                parts.update(fact=1.0, evidence=1.0, coverage=1.0, relations=1.0)
        else:
            if not ids:
                parts["criticalErrors"].append("empty_selection_for_answerable_task")
            selected_families = {observed[eid]["family"] for eid in ids if eid in observed}
            for relation in relations:
                if not set(RELATIONS.get(relation, ())) <= selected_families:
                    parts["criticalErrors"].append("relation_missing_operands")
            need_ids, need_relations = set(expected["evidenceIds"]), set(expected["relations"])
            parts["fact"] = len(set(ids) & need_ids) / max(1, len(need_ids))
            parts["evidence"] = float(bool(ids) and all(eid in observed for eid in ids))
            parts["relations"] = len(set(relations) & need_relations) / len(need_relations) if need_relations else 1.0
            parts["coverage"] = (len(set(ids) & need_ids) + len(set(relations) & need_relations)) / max(1, len(need_ids) + len(need_relations))
        if parts["criticalErrors"]:
            return parts
        parts["valid"] = parts["coverage"] == 1.0 and families <= actual_families
        parts["total"] = round(.30 * parts["fact"] + .25 * parts["evidence"] + .20 * parts["coverage"]
                               + .15 * parts["relations"] + .10 * parts["format"] - cost, 6)
        return parts


def teacher_actions(task, store=None):
    if store is not None and task["storeSha256"] != store_digest(store):
        raise ValueError("Teacher/store mismatch")
    return [{"tools": list(task["oracle"]["requiredFamilies"])}, copy.deepcopy(task["oracle"]["answer"])]


def run_episode(task, store, actions):
    """Offline action runner used to verify teachers, parsers and reward boundaries."""
    episode = Environment(task, store)
    for action in actions:
        kind, value, invalid = parse_action(action)
        if invalid:
            return episode.score(None, invalid=True)
        if kind == "answer":
            return episode.score(value)
        for family in value:
            episode.execute(family)
    return episode.score(None, invalid=True)
